-- Baseline: the schema previously created by Hibernate (ddl-auto=update).
-- Existing databases are baselined at this version (spring.flyway.baseline-on-migrate),
-- so this script only runs on new, empty databases.

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password       VARCHAR(255),
    first_name     VARCHAR(255) NOT NULL,
    last_name      VARCHAR(255) NOT NULL,
    phone_number   VARCHAR(255),
    bio            VARCHAR(255),
    facebook_link  VARCHAR(255),
    instagram_link VARCHAR(255),
    x_link         VARCHAR(255),
    linkedin_link  VARCHAR(255),
    provider       VARCHAR(255) CHECK (provider IN ('LOCAL', 'GOOGLE')),
    provider_id    VARCHAR(255),
    avatar         VARCHAR(255),
    created_at     TIMESTAMP(6) NOT NULL
);

CREATE TABLE password_reset_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(255) NOT NULL UNIQUE,
    user_id     BIGINT       NOT NULL UNIQUE REFERENCES users (id),
    expiry_date TIMESTAMP(6) NOT NULL
);

CREATE TABLE itineraries (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT,
    destination          VARCHAR(255),
    total_budget         VARCHAR(255),
    total_days           INTEGER,
    total_estimated_cost VARCHAR(255),
    budget_status        VARCHAR(255),
    accommodation        JSONB,
    itinerary            JSONB,
    tips                 JSONB
);
