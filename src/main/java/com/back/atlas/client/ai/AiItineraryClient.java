package com.back.atlas.client.ai;

import com.back.atlas.config.AiServiceConfig;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientException;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;

/**
 * HTTP client for the Python AI microservice.
 * All prompt engineering and LLM handling live there: this class only sends requests.
 */
@Slf4j
@Component
public class AiItineraryClient {

    private final RestClient restClient;
    private final ObjectMapper mapper = AiServiceConfig.snakeCaseMapper();

    public AiItineraryClient(@Qualifier("aiServiceRestClient") RestClient restClient) {
        this.restClient = restClient;
    }

    public AiServiceResponse generateItinerary(AiServiceRequest request) {
        AiServiceResponse response = post("/v1/itineraries", request);
        log.info("Itinerary for '{}' generated by {} (source={}, attempts={}, {} ms)",
                request.destination(), response.metadata().model(), response.metadata().source(),
                response.metadata().attempts(), response.metadata().latencyMs());
        return response;
    }

    public AiServiceResponse regenerateDay(AiRegenerateDayRequest request) {
        return post("/v1/itineraries/regenerate-day", request);
    }

    /**
     * Streams a generation (Server-Sent Events) and forwards each event to the listener.
     * Blocks until the stream ends: call it from a background thread.
     */
    public void streamItinerary(AiServiceRequest request, AiStreamListener listener) {
        try {
            restClient.post()
                    .uri("/v1/itineraries/stream")
                    .accept(MediaType.TEXT_EVENT_STREAM)
                    .body(request)
                    .exchange((req, res) -> {
                        if (res.getStatusCode().isError()) {
                            throw new AiServiceException("AI service answered " + res.getStatusCode(), null);
                        }
                        try (BufferedReader reader = new BufferedReader(
                                new InputStreamReader(res.getBody(), StandardCharsets.UTF_8))) {
                            readEvents(reader, listener);
                        }
                        return null;
                    });
        } catch (RestClientException | UncheckedIOException e) {
            log.error("AI service stream failed: {}", e.getMessage());
            throw new AiServiceException("AI service call failed", e);
        }
    }

    /** Minimal SSE parser: "event:" and "data:" lines, an empty line ends the event. */
    private void readEvents(BufferedReader reader, AiStreamListener listener) throws IOException {
        String event = "message";
        StringBuilder data = new StringBuilder();
        String line;
        while ((line = reader.readLine()) != null) {
            if (line.startsWith("event:")) {
                event = line.substring(6).trim();
            } else if (line.startsWith("data:")) {
                data.append(line.substring(5).trim());
            } else if (line.isEmpty() && !data.isEmpty()) {
                dispatch(event, data.toString(), listener);
                event = "message";
                data.setLength(0);
            }
        }
    }

    private void dispatch(String event, String data, AiStreamListener listener) throws IOException {
        switch (event) {
            case "day" -> listener.onDay(mapper.readValue(data, AiServiceResponse.Day.class));
            case "status" -> listener.onStatus(mapper.readTree(data).path("message").asText());
            case "result" -> listener.onResult(mapper.readValue(data, AiServiceResponse.class));
            case "error" -> {
                JsonNode detail = mapper.readTree(data).path("detail");
                throw new AiServiceException("AI generation failed: " + detail.asText(), null);
            }
            default -> log.debug("Ignoring unknown SSE event '{}'", event);
        }
    }

    private AiServiceResponse post(String path, Object body) {
        try {
            AiServiceResponse response = restClient.post()
                    .uri(path)
                    .body(body)
                    .retrieve()
                    .body(AiServiceResponse.class);
            if (response == null) {
                throw new AiServiceException("Empty response from AI service", null);
            }
            return response;
        } catch (RestClientException e) {
            log.error("AI service call to {} failed: {}", path, e.getMessage());
            throw new AiServiceException("AI service call failed", e);
        }
    }
}
